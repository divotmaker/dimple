//! Reference impact sequences for the planar regression test.
//!
//! Each entry is a preset shot (`ShotInput::driver`, `seven_iron`, `wedge`
//! with `BallModel::TOUR` at sea level) landing on `Surface::FAIRWAY` or
//! `Surface::GREEN` with zero sidespin and zero azimuth, solved with the
//! planar (2D) form of the same impact model: Penner's eq. 8 tilt, Daish's
//! grip/slip impulse in the tilted frame, and the eq. 7 rotation back, in
//! scalar along-track coordinates, with the hops as exact parabolas.
//!
//! `impacts` holds, per impact, the rebound velocity (m/s), the spin after
//! the impact as a scalar about the across-track axis signed positive for
//! topspin on a ball moving downrange (that is, `−ω_z`, rad/s), and the
//! impact position (m). The last rebound is the unprojected one; its `y`
//! is below the 5 mm hop speed. `rest` comes from a first-order integration
//! of the slide/roll with a 5 cm/s stop speed and a 0.1 m/s roll threshold,
//! so it agrees with the RK4 ground phase only to about 2 cm.

