//! Reference impact sequences for the planar regression test.
//!
//! Each entry is a preset shot (`ShotInput::driver`, `seven_iron`, `wedge`
//! with `Tour::SEA_LEVEL`) landing on `Surface::FAIRWAY` or
//! `Surface::GREEN` with zero sidespin and zero azimuth, solved with the
//! planar (2D) form of the same impact model: the contact angle
//! `tan β = (v_t / 50 m/s) · (1 − exp(−(θ / 20°)³))` times the surface's
//! compliance, capped at the incidence angle, Penner's eq. 5 restitution,
//! the grip/slip impulse in the tilted frame, and the rotation back, in
//! scalar along-track coordinates, with the hops as exact parabolas.
//!
//! `impacts` holds, per impact, the rebound velocity (m/s), the spin after
//! the impact as a scalar about the across-track axis signed positive for
//! topspin on a ball moving downrange (that is, `−ω_z`, rad/s), and the
//! impact position (m). The last rebound is the unprojected one; its `y`
//! is below the 5 mm hop speed. `rest` comes from a first-order (Euler)
//! integration of the slide and roll (each surface's roll law and plowing)
//! in 10 µs steps, finished at constant
//! deceleration below 5 cm/s, so it agrees with the RK4 ground phase to
//! about 0.01 mm.

